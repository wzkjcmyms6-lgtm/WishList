// La misma para los dos y sin repetir hasta terminar la vuelta.
export function preguntaDelDia(indiceDelDia) {
  const total = PREGUNTAS.length;
  const indice = ((indiceDelDia % total) + total) % total;
  return { indice, texto: PREGUNTAS[indice] };
}
